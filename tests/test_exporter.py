def test_language_detection():
    assert _get_markdown_language("main.py") == "python"
    assert _get_markdown_language("App.tsx") == "tsx"
    assert _get_markdown_language("styles.css") == "css"
    assert _get_markdown_language("config.yaml") == "yaml"
    assert _get_markdown_language("Dockerfile") == "dockerfile"
    assert _get_markdown_language("app.dockerfile") == "dockerfile"
    assert _get_markdown_language(".gitignore") == "gitignore"
    assert _get_markdown_language("unknown_file.xyz123") == "text"


def test_binary_detection():
    assert _looks_binary("image.png") is True
    assert _looks_binary("program.exe") is True
    assert _looks_binary("archive.zip") is True
    assert _looks_binary("icon.ico") is True

    with tempfile.NamedTemporaryFile(suffix=".txt", delete=False) as f:
        f.write(b"Normal text content")
        txt_path = f.name

    with tempfile.NamedTemporaryFile(suffix=".txt", delete=False) as f:
        f.write(b"Binary \x00 with null bytes")
        bin_path = f.name

    try:
        assert _looks_binary(txt_path) is False
        assert _looks_binary(bin_path) is True
    finally:
        os.remove(txt_path)
        os.remove(bin_path)


